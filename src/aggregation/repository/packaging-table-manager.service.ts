import { BadRequestException, Injectable } from '@nestjs/common';
import { EntityManager } from 'typeorm';

@Injectable()
export class PackagingTableManager {
  async createTable(manager: EntityManager, gtin: string): Promise<string> {
    if (!/^\d{14}$/.test(gtin)) {
      throw new BadRequestException('GTIN должен содержать 14 цифр');
    }

    const timestamp = new Date().toISOString().replace(/\D/g, '').slice(0, 17);

    const tableName = `packaging_${gtin}_${timestamp}`;
    const table = this.getQuotedTableName(tableName);

    await manager.query(`
      CREATE TABLE ${table} (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        code TEXT NOT NULL,
        small_box_label TEXT NULL,
        big_box_label TEXT NULL,
        pallet_label TEXT NULL,
        tsd_id INTEGER NOT NULL,
        created_at TIMESTAMP WITHOUT TIME ZONE
          NOT NULL DEFAULT CURRENT_TIMESTAMP
      )
    `);

    await manager.query(`
      CREATE INDEX "${tableName}_code_idx"
      ON ${table} (code)
    `);

    await manager.query(`
      CREATE INDEX "${tableName}_small_label_idx"
      ON ${table} (small_box_label)
      WHERE small_box_label IS NOT NULL
    `);

    await manager.query(`
      CREATE INDEX "${tableName}_big_label_idx"
      ON ${table} (big_box_label)
      WHERE big_box_label IS NOT NULL
    `);

    await manager.query(`
      CREATE INDEX "${tableName}_pallet_label_idx"
      ON ${table} (pallet_label)
      WHERE pallet_label IS NOT NULL
    `);

    await manager.query(`
      CREATE INDEX "${tableName}_open_products_idx"
      ON ${table} (tsd_id)
      WHERE small_box_label IS NULL
    `);

    return tableName;
  }

  getQuotedTableName(tableName: string): string {
    if (!/^packaging_\d{14}_\d{17}$/.test(tableName)) {
      throw new BadRequestException('Некорректное имя таблицы фасовки');
    }

    return `"${tableName}"`;
  }
}
